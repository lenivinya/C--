/*Задача 7*/
/* Напишите программу, которая заполнит массив А из 100
элементов случайными числами, в диапазоне от 1 до 50. После этого
перепишите их в двухмерный массив А_2... */

#include <iostream>
#include <cstdlib>
#include <ctime>

using namespace std;

int main() {
    srand(time(0));
    
    int A[100];
    // заполняем массив случайными числами от 1 до 50
    for (int i = 0; i < 100; ++i) {
        A[i] = rand() % 50 + 1;
    }

    // создаем двумерный массив:
    // макс. число 50, максимальный делитель тоже 50 (50 столбцов)
    // макс. количество чисел в одном столбце - 100
    const int cols = 50;
    int A_2[100][cols];
    
    // инициализация пустых ячеек значением -1
    for (int i = 0; i < 100; ++i) {
        for (int j = 0; j < cols; ++j) {
            A_2[i][j] = -1;
        }
    }

    // массив для отслеживания текущей свободной строки в каждом столбце
    int rowCount[cols] = {0}; 

    // распределяем элементы
    for (int i = 0; i < 100; ++i) {
        for (int j = 0; j < cols; ++j) {
            int divisor = j + 1;
            if (A[i] % divisor == 0) {
                // записываем число и сдвигаем индекс строки для этого столбца
                A_2[rowCount[j]][j] = A[i];
                rowCount[j]++;
            }
        }
    }

    // ищем максимальную заполненную строку, чтобы не выводить лишние пустые ряды
    int maxRowsUsed = 0;
    for (int j = 0; j < cols; ++j) {
        if (rowCount[j] > maxRowsUsed) {
            maxRowsUsed = rowCount[j];
        }
    }

    cout << "Двухмерный массив A_2 (показаны первые 10 столбцов для компактности):\n";
    for (int i = 0; i < maxRowsUsed; ++i) {
        // ограничиваем вывод 10 столбцами, иначе таблица не влезет в обычный экран консоли
        for (int j = 0; j < 10; ++j) { 
            if (A_2[i][j] != -1) {
                cout << A_2[i][j] << "\t";
            } else {
                cout << " \t"; // пробел вместо -1
            }
        }
        cout << endl;
    }

    return 0;
}