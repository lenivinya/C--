/* Напишите программу – симулятор броска шестигранного
кубика (или другого, например, 20гранного). Программа должна запросить
сколько раз вы хотели бы бросить кубик. Далее программа рандомно выводит
на экран выпавшее количество очков. В конце выводится общая сумма всех очков. */

#include <iostream>
#include <cstdlib>
#include <ctime>

using namespace std;

int main() {
    srand(time(0)); 
    
    int rolls;
    int sides = 6; // количество граней кубика (можно поменять на 20)
    int totalSum = 0;

    cout << "Сколько раз вы хотите бросить кубик? ";
    cin >> rolls;

    for (int i = 1; i <= rolls; ++i) {
        // генерация числа от 1 до sides
        int result = rand() % sides + 1; 
        cout << "Бросок " << i << ": выпало " << result << endl;
        totalSum += result;
    }

    cout << "--------------------------\n";
    cout << "Общая сумма всех очков: " << totalSum << endl;

    return 0;
}