/* Напишите функцию с именем zero(), 
в которую передаются с помощью ссылок два аргумента типа int, 
присваивающую меньшему из аргументов нулевое значение. 
Напишите программу для проверки работы функции. */

#include <iostream>
using namespace std;

void zero(int &a, int &b) { // присваивает 0 меньшему из двух аргументов
    if (a < b)
        a = 0;
    else if (b < a)
        b = 0; // если равны – оставляем как есть
}

int main() {
    int x, y;
    cout << "Введите два целых числа: ";
    cin >> x >> y;

    cout << "До вызова: x = " << x << ", y = " << y << endl;
    zero(x, y);
    cout << "После вызова: x = " << x << ", y = " << y << endl;
    return 0;
}